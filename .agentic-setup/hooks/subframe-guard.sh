#!/bin/sh
# PreToolUse on file edits (Claude and Codex): denies a hand edit to a Subframe-generated
# ComponentName.tsx (a [A-Z]*.tsx under the `directory` of the nearest .subframe/sync.json that
# lacks @subframe/sync-disable). index.tsx wrappers and index.ts barrels always pass.
input=$(cat)
# Desktop worktree sessions run the main checkout's hooks: hand over to the worktree's own copy.
here=$(printf '%s' "$input" | jq -r '.cwd // "."')
local_copy="$(git -C "$here" rev-parse --show-toplevel 2>/dev/null)/.agentic-setup/hooks/$(basename "$0")"
if [ -z "$AGENTIC_HOOK_LOCAL" ] && [ -f "$local_copy" ] && [ ! "$local_copy" -ef "$0" ]; then
  printf '%s' "$input" | AGENTIC_HOOK_LOCAL=1 sh "$local_copy"; exit $?
fi
# Claude sends tool_input.file_path; Codex may send apply_patch text in command, patch, or input.
out=$(printf '%s' "$input" | jq -r '(.cwd // "."), (.tool_input.file_path // .tool_input.path // .tool_input.filePath // empty),
  ([.tool_input.command, .tool_input.patch, .tool_input.input][] | if type == "string" then scan("(?m)^\\*\\*\\* (?:Add|Update) File: (.+)$")[0] else empty end)')
cwd=$(printf '%s\n' "$out" | head -1)
set --
while IFS= read -r f; do
  [ -n "$f" ] || continue
  case "$f" in /*) ;; *) f="$cwd/$f" ;; esac
  set -- "$@" "$f"
done <<EOF2
$(printf '%s\n' "$out" | tail -n +2)
EOF2
[ $# -gt 0 ] || exit 0
for file in "$@"; do
  case "$(basename "$file")" in [A-Z]*.tsx) ;; *) continue ;; esac
  [ -f "$file" ] && grep -q '@subframe/sync-disable' "$file" && continue
  dir=$(dirname "$file")
  while [ "$dir" != "/" ] && [ ! -d "$dir" ]; do dir=$(dirname "$dir"); done
  # A new component's folder may not exist yet: compare from the nearest folder that does.
  real=$(cd "$dir" && pwd -P)
  while [ "$dir" != "/" ] && [ ! -f "$dir/.subframe/sync.json" ]; do dir=$(dirname "$dir"); done
  [ -f "$dir/.subframe/sync.json" ] || continue
  gen=$(jq -r '.directory // empty' "$dir/.subframe/sync.json")
  gen=$(cd "$dir" && cd "${gen:-.}" 2>/dev/null && pwd -P) || continue
  case "$real/" in "$gen"/*) ;; *) continue ;; esac
  jq -n --arg f "$(basename "$file")" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny",
    permissionDecisionReason: ($f + " is generated by Subframe. Change it in Subframe and re-sync, or customize its index.tsx wrapper and mark that file // @subframe/sync-disable.")}}'
  exit 0
done
